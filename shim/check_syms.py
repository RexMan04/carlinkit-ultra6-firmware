#!/usr/bin/env python3
# Static link check for libcpthru.so against the stock rootfs
# (PASSTHROUGH_PLAN.md "Verification" 2). Fails on:
#  - an undefined symbol no library in sdDongle's load set exports
#    (e.g. musl 1.2 time64 names the device's musl 1.1.24 lacks)
#  - a hook whose intended caller doesn't bind it through a JUMP_SLOT
#    (then LD_PRELOAD can't intercept it)
#  - a hook or dlsym'd helper with no original in the load set
# Usage: check_syms.py libcpthru.so ROOTFS
#        check_syms.py --got-table ROOTFS   (writes the qemu test's slot table)
import os, re, subprocess, sys

HOOKS = {  # symbol -> binary whose PLT must reach it
    "_ZN12ScreenRecord18setCarlinkH264DataEPci": "usr/bin/sdDongle",
    "carplay_reverse_video_start": "usr/bin/sdDongle",
    "carplay_reverse_video_force_start": "usr/bin/sdDongle",
    "carplay_reverse_video_stop": "usr/bin/sdDongle",
    "carplay_reverse_video_push_frame": "usr/bin/sdDongle",
    "wrap_system_property_set": "usr/lib/libSdCarplay.so",
    "sd_get_info_int": "usr/lib/libSdCarplay.so",
    "ScreenStreamStart": "usr/lib/libAirPlay.so",
    "ScreenStreamStop": "usr/lib/libAirPlay.so",
    "ScreenStreamSetAVCC": "usr/lib/libAirPlay.so",
    "AirPlayReceiverSessionPlatformInitialize": "usr/lib/libAirPlay.so",
    "AirPlayReceiverSessionPlatformFinalize": "usr/lib/libAirPlay.so",
}
HELPERS = ["AirPlayReceiverSessionForceKeyFrame", "carplay_reverse_get_video_parameters",
           "prop_get_int", "get_current_mono_time_ms"]


def out(*cmd):
    return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout


def slot(root, caller, sym):
    """GOT address of sym's JUMP_SLOT in caller, or None."""
    m = re.search(r"^([0-9a-f]+)\s+\S+\s+R_ARM_JUMP_SLOT\s+\S+\s+" + re.escape(sym) + r"\b",
                  out("readelf", "-rW", os.path.join(root, caller)), re.M)
    return int(m.group(1), 16) if m else None


def load_set(root):
    """sdDongle and its NEEDED closure, in load order."""
    def find(name):
        for d in ("lib", "usr/lib"):
            p = os.path.join(root, d, name)
            if os.path.exists(p):
                return os.path.realpath(p)
        raise SystemExit(f"FAIL: {name} not found in rootfs")

    load, todo = [], [os.path.join(root, "usr/bin/sdDongle")]
    while todo:
        p = todo.pop(0)
        if p not in load:
            load.append(p)
            todo += [find(n) for n in re.findall(r"\(NEEDED\).*\[(.+?)\]", out("readelf", "-d", p))]
    return load


def got_table(root):
    print("/* generated by check_syms.py --got-table */")
    print("static const struct { const char *obj, *sym; unsigned long off; } slots[] = {")
    for sym, caller in HOOKS.items():
        print(f'\t{{"{os.path.basename(caller)}", "{sym}", {slot(root, caller, sym):#x}UL}},')
    print("};")


def check(so, root):
    exports = {}
    for p in load_set(root):
        for line in out("nm", "-D", "--defined-only", p).splitlines():
            parts = line.split()
            if len(parts) == 3 and parts[1] in "TWDBVRiu":
                exports.setdefault(parts[2], os.path.basename(p))

    bad = 0
    skip = ("__cxa_finalize", "__deregister_frame_info", "__register_frame_info")
    undef = [s for s in out("nm", "-D", "--undefined-only", so).split()
             if s not in ("U", "w") and not s.startswith("_ITM") and s not in skip]
    for s in undef:
        if s not in exports:
            print(f"FAIL undefined {s}: no library in sdDongle's load set exports it")
            bad += 1
    print(f"undefined symbols resolved: {len(undef) - bad}/{len(undef)}")

    mine = {l.split()[-1] for l in out("nm", "-D", "--defined-only", so).splitlines()}
    for sym, caller in HOOKS.items():
        if sym not in mine:
            print(f"FAIL hook {sym} not exported by the shim"); bad += 1
        if slot(root, caller, sym) is None:
            print(f"FAIL hook {sym}: {caller} has no JUMP_SLOT for it"); bad += 1
        if sym not in exports:
            print(f"FAIL hook {sym}: no original for RTLD_NEXT"); bad += 1
        else:
            print(f"ok hook {sym:45s} caller {os.path.basename(caller):16s} original {exports[sym]}")
    for sym in HELPERS:
        if sym not in exports:
            print(f"FAIL helper {sym} not exported"); bad += 1
        else:
            print(f"ok helper {sym:43s} from {exports[sym]}")

    if "Tag_ABI_VFP_args: VFP registers" not in out("readelf", "-A", so):
        print("FAIL not hard-float"); bad += 1
    print("PASS" if not bad else f"{bad} problem(s)")
    return bad


if __name__ == "__main__":
    if sys.argv[1] == "--got-table":
        got_table(sys.argv[2])
    else:
        sys.exit(1 if check(sys.argv[1], sys.argv[2]) else 0)
